#!/usr/bin/env node
// Prepare Instagram posts in the repo, then schedule them by hand in the Instagram app.
//
//   node tools/instagram/instagram.mjs list
//   node tools/instagram/instagram.mjs check [<post-folder>...]
//   node tools/instagram/instagram.mjs queue [--write]
//   node tools/instagram/instagram.mjs done  <post-folder>...
//
// See tools/instagram/README.md.

import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { join, relative, dirname, basename, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import { loadPost, checkPost } from './lib.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = process.env.IG_REPO_ROOT || join(HERE, '..', '..');
const QUEUE_FILE = join(REPO, 'instagram-queue.md');
const TZ = 'Asia/Jakarta';

// ---------- helpers ----------

function rel(p) {
  return relative(process.cwd(), p) || '.';
}

// Path from the repo root with forward slashes, for links.
function repoPath(p) {
  return relative(REPO, p).split(sep).join('/');
}

function urlPath(p) {
  return repoPath(p).split('/').map(encodeURIComponent).join('/');
}

// Every folder under <product>/instagram/ that has a post.json.
function findPostFolders() {
  const out = [];
  for (const product of readdirSync(REPO, { withFileTypes: true })) {
    if (!product.isDirectory() || product.name.startsWith('.') || ['tools', 'node_modules'].includes(product.name)) continue;
    const ig = join(REPO, product.name, 'instagram');
    if (!existsSync(ig)) continue;
    for (const d of readdirSync(ig, { withFileTypes: true })) {
      if (d.isDirectory() && existsSync(join(ig, d.name, 'post.json'))) out.push(join(ig, d.name));
    }
  }
  return out.sort();
}

// "owner/repo" for download links, from the Action's env or the git remote.
function githubRepo() {
  if (process.env.GITHUB_REPOSITORY) return process.env.GITHUB_REPOSITORY;
  try {
    const remote = execFileSync('git', ['remote', 'get-url', 'origin'], { cwd: REPO, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
    const m = remote.match(/github\.com[:/]([^/]+\/[^/]+?)(\.git)?$/) || remote.match(/\/git\/([^/]+\/[^/]+?)(\.git)?$/);
    return m ? m[1] : null;
  } catch {
    return null;
  }
}

function fmtWhen(iso) {
  return new Intl.DateTimeFormat('en-GB', {
    timeZone: TZ, weekday: 'short', day: 'numeric', month: 'short', year: 'numeric', hour: '2-digit', minute: '2-digit', hour12: false,
  }).format(new Date(iso)).replace(/^(\w+),/, '$1').replace(/,? (\d{2}:\d{2})$/, ', $1') + ' WIB';
}

// Monday of the WIB week the time falls in, as "Mon 26 Oct 2026".
function weekOf(iso) {
  const wib = new Date(new Date(iso).getTime() + 7 * 3600e3); // shift so UTC fields read as WIB
  const day = (wib.getUTCDay() + 6) % 7; // 0 = Monday
  const monday = new Date(Date.UTC(wib.getUTCFullYear(), wib.getUTCMonth(), wib.getUTCDate() - day));
  return new Intl.DateTimeFormat('en-GB', { timeZone: 'UTC', weekday: 'short', day: 'numeric', month: 'short', year: 'numeric' }).format(monday).replace(',', '');
}

function fence(text) {
  const ticks = (text.match(/`{3,}/g) || []).reduce((m, t) => Math.max(m, t.length + 1), 3);
  return '`'.repeat(ticks) + 'text\n' + text + '\n' + '`'.repeat(ticks);
}

function printCheck(post, result) {
  console.log(`\n${rel(post.dir)}`);
  console.log(`  at: ${post.at ?? '?'}${result.when ? `  (${fmtWhen(result.when)})` : ''}   status: ${post.status}`);
  console.log(`  images: ${post.images.map((i) => i.name || i.path).join(', ') || 'none'}`);
  console.log(`  caption: ${[...post.caption].length} chars`);
  for (const w of result.warnings) console.log(`  ⚠ ${w}`);
  for (const e of result.errors) console.log(`  ✖ ${e}`);
  if (!result.errors.length) console.log('  ✔ ok');
}

// ---------- queue page ----------

export function buildQueue(folders, { now = new Date(), repo = githubRepo() } = {}) {
  const upcoming = [];
  const missed = [];
  const broken = [];
  for (const dir of folders) {
    let post;
    try { post = loadPost(dir); } catch (e) { broken.push({ dir, why: e.message }); continue; }
    if (post.status !== 'ready') continue;
    const result = checkPost(post, { now });
    if (result.errors.length) { broken.push({ dir, why: result.errors.join(' ') }); continue; }
    (new Date(result.when) < now ? missed : upcoming).push({ post, when: result.when });
  }
  upcoming.sort((a, b) => a.when.localeCompare(b.when));
  missed.sort((a, b) => a.when.localeCompare(b.when));

  const download = (p) => (repo ? `https://raw.githubusercontent.com/${repo}/main/${urlPath(p)}` : urlPath(p));
  const L = [];
  L.push('# Instagram queue', '');
  L.push('<!-- Generated by tools/instagram/instagram.mjs queue. Do not edit by hand: change the post folders instead. -->', '');
  L.push('Posts that are ready and not yet scheduled in the Instagram app, soonest first.', '');
  L.push('**To schedule one:** save its images, then in Instagram tap **+ → Post**, pick the images in the order shown, ' +
    'tap **Next**, paste the caption, open **More options → Schedule this post**, set the time, and tap **Schedule**. ' +
    'Then mark it done: ask Claude, or set `"status": "scheduled"` in its `post.json`.', '');

  if (!upcoming.length && !missed.length) L.push('_Nothing to schedule right now._', '');

  const entry = ({ post, when }) => {
    const product = basename(dirname(dirname(post.dir))); // <product>/instagram/<post>
    L.push(`### ${fmtWhen(when)} · ${product}`, '');
    L.push(`Folder: [\`${repoPath(post.dir)}\`](${urlPath(post.dir)})`, '');
    post.images.forEach((img, i) => {
      L.push(`${i + 1}. [Download ${img.name}](${download(img.path)})`, '');
      L.push(`   <img src="${urlPath(img.path)}" width="240" alt="${img.name}">`, '');
    });
    L.push('Caption:', '', fence(post.caption || ''), '');
  };

  if (missed.length) {
    L.push('## Missed', '', 'Their time has passed. Give them a new `at`, or mark them scheduled if they already went out.', '');
    missed.forEach(entry);
  }
  let week = null;
  for (const item of upcoming) {
    const w = weekOf(item.when);
    if (w !== week) { L.push(`## Week of ${w}`, ''); week = w; }
    entry(item);
  }
  if (broken.length) {
    L.push('## Needs fixing', '', 'These are marked ready but have a problem. Run `npm run ig -- check` for details.', '');
    for (const b of broken) L.push(`- \`${repoPath(b.dir)}\`: ${b.why}`);
    L.push('');
  }
  return L.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n';
}

// ---------- commands ----------

function cmdList() {
  const folders = findPostFolders();
  if (!folders.length) return console.log('No post folders found under */instagram/.');
  for (const dir of folders) {
    try {
      const post = loadPost(dir);
      console.log(`${rel(dir).padEnd(55)} ${String(post.at).padEnd(18)} ${post.status}`);
    } catch (e) {
      console.log(`${rel(dir).padEnd(55)} ✖ ${e.message}`);
    }
  }
}

function cmdCheck(dirs) {
  const folders = dirs.length ? dirs : findPostFolders();
  let bad = 0;
  for (const dir of folders) {
    let post;
    try { post = loadPost(dir); } catch (e) { console.log(`\n${dir}\n  ✖ ${e.message}`); bad++; continue; }
    const result = checkPost(post);
    printCheck(post, result);
    if (result.errors.length) bad++;
  }
  console.log(`\n${folders.length} checked, ${bad} with problems.`);
  if (bad) process.exitCode = 1;
}

function cmdQueue(flags) {
  const md = buildQueue(findPostFolders());
  if (!flags.write) return process.stdout.write(md);
  const old = existsSync(QUEUE_FILE) ? readFileSync(QUEUE_FILE, 'utf8') : '';
  if (old === md) return console.log(`${rel(QUEUE_FILE)} is up to date.`);
  writeFileSync(QUEUE_FILE, md);
  console.log(`Wrote ${rel(QUEUE_FILE)}.`);
}

// Mark posts as scheduled in the app, so they leave the queue.
function cmdDone(dirs) {
  if (!dirs.length) throw new Error('Give the post folder(s) you scheduled.');
  for (const dir of dirs) {
    const file = join(dir, 'post.json');
    if (!existsSync(file)) throw new Error(`No post.json in ${dir}`);
    const meta = JSON.parse(readFileSync(file, 'utf8'));
    meta.status = 'scheduled';
    writeFileSync(file, JSON.stringify(meta, null, 2) + '\n');
    console.log(`✔ ${rel(dir)} marked scheduled.`);
  }
}

// ---------- main ----------

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  const [cmd, ...rest] = process.argv.slice(2);
  const flags = { write: rest.includes('--write') };
  const dirs = rest.filter((a) => !a.startsWith('--'));
  try {
    switch (cmd) {
      case 'list': cmdList(); break;
      case 'check': cmdCheck(dirs); break;
      case 'queue': cmdQueue(flags); break;
      case 'done': cmdDone(dirs); break;
      default:
        console.log(`Usage:
  node tools/instagram/instagram.mjs list                 list post folders and their status
  node tools/instagram/instagram.mjs check [<folder>...]  check posts against Instagram's limits (all by default)
  node tools/instagram/instagram.mjs queue [--write]      print the queue page (--write saves instagram-queue.md)
  node tools/instagram/instagram.mjs done <folder>...     mark posts as scheduled in the app`);
        if (cmd) process.exitCode = 1;
    }
  } catch (e) {
    console.error(`✖ ${e.message}`);
    process.exitCode = 1;
  }
}
